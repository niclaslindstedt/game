// The COMPANION pipeline. Compiles `content/companions.yaml` — the hand-authored
// roster of who a spared unique BECOMES when it joins the party — into
// `src/generated/companions.ts` (GENERATED_COMPANIONS), which
// `src/game/defs/companions.ts` re-exposes as COMPANION_DEFS. It:
//   1. harvests the sprite stems from the content/sprites tree, so a companion
//      whose two-frame family isn't in the atlas fails the build rather than
//      walking beside the hero as nothing at all,
//   2. schema-validates every companion (a missing field, an unknown weapon, a
//      power that grows a kit the def hasn't got — see
//      asset-tools/companion-schema.mjs),
//   3. writes the flat `{ id → CompanionDef }` catalog, stamping each def's `id`
//      from its catalog key so the YAML never repeats itself.
// The output is gitignored and regenerated on every build (like enemies.ts and
// levels.ts), so the YAML is the single source of truth.
//
//   node scripts/generate-companions.mjs
//
// MUST run AFTER generate-items.mjs: a companion's signature `weapon` is checked
// against the live weapon catalog, which reads the file that script writes. It
// need not run before the enemy pipeline — `generate-enemies.mjs` reads the
// companion ids an elite's `spareable:` may name from `content/companions.yaml`
// through the same loader, rather than from the module this script feeds, so
// neither generator waits on the other.

import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { register } from "node:module";
import process from "node:process";
import { fileURLToPath, pathToFileURL } from "node:url";

// Engine modules under src/lib use the @game/lib alias at runtime — map it so
// the equipment catalog imports cleanly under plain node.
register("./game-alias-loader.mjs", import.meta.url);

import { validateCompanion } from "./asset-tools/companion-schema.mjs";
import { loadCompanions } from "./companion-data/load-yaml.mjs";

const engine = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url));

// The weapon ids a companion's signature piece may name. Imported DIRECTLY (never
// @game/core) so nothing pulls the file we are about to write — the same
// bootstrap rule generate-enemies.mjs and generate-levels.mjs follow. It is the
// engine's catalog rather than the content tree's because the built-in `blaster`
// sidearm is authored in `equipment.ts` as engine machinery, and a companion may
// legitimately carry it.
const { WEAPON_DEFS } = await import(
  pathToFileURL(engine("src/game/defs/equipment.ts")).href
);

// ---- Sprite stems (content/sprites/<family>/<name>.yaml, stem == sprite id;
// underscore-prefixed files are family/core preambles, not sprites). ----------
const spritesDir = engine("content/sprites");
const sprites = new Set();
for (const family of readdirSync(spritesDir, { withFileTypes: true })) {
  if (!family.isDirectory()) continue;
  for (const file of readdirSync(`${spritesDir}/${family.name}`)) {
    if (!file.endsWith(".yaml") || file.startsWith("_")) continue;
    sprites.add(file.slice(0, -".yaml".length));
  }
}

// ---- Load ------------------------------------------------------------------
const { companions, entries } = loadCompanions(engine("content"));

// ---- Validate --------------------------------------------------------------
const refs = { sprites, weapons: new Set(Object.keys(WEAPON_DEFS)) };
const errors = [];
const warnings = [];
for (const { id, def } of entries) {
  const res = validateCompanion(id, def, refs);
  errors.push(...res.errors);
  warnings.push(...res.warnings);
}
for (const w of warnings) console.warn(`! ${w}`);
if (errors.length > 0) {
  console.error(
    `${errors.length} companion schema error(s):\n  ${errors.join("\n  ")}`,
  );
  process.exit(1);
}

const banner = `// @generated by scripts/generate-companions.mjs — DO NOT EDIT.
// Source of truth: content/companions.yaml. Regenerate with
// \`npm run levels\` (also runs inside \`npm run assets\` / \`make assets\`).
// SPDX-License-Identifier: PolyForm-Noncommercial-1.0.0`;

const out = `${banner}
import type { CompanionDef } from "../game/defs/companions.ts";

export const GENERATED_COMPANIONS: Record<string, CompanionDef> = ${JSON.stringify(
  companions,
  null,
  2,
)} as unknown as Record<string, CompanionDef>;
`;

const destDir = engine("src/generated");
mkdirSync(destDir, { recursive: true });
writeFileSync(`${destDir}/companions.ts`, out);
console.log(
  `wrote src/generated/companions.ts — ` +
    `${Object.keys(companions).length} companions`,
);
