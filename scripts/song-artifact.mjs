/** The current track (minus its mutes), rendered offline to a WAV blob. */
async function renderWav() {
  const t = track();
  const sr = 44100;
    const loop = loopSeconds(t);
    const ctx = new OfflineAudioContext(2, Math.ceil((loop + 2) * sr), sr);
    // The synth builds its own context; hand it this one, reporting "running"
    // so it does not sit waiting for a gesture that an offline render has no
    // way to give it.
    const Real = window.AudioContext;
    Object.defineProperty(ctx, "state", { get: () => "running" });
    window.AudioContext = function () { return ctx; };
    const s = GameAudio.createSynth();
    s.unlock();
    window.AudioContext = Real;

    const flat = GameAudio.flattenTrack(live());
    const stepS = 60 / t.bpm / t.stepsPerBeat;
    for (const { instrument, tokens } of flat.voices) {
      for (let i = 0; i < tokens.length; i++) {
        const token = tokens[i];
        if (!token || token === "." || token === "=") continue;
        let steps = 1;
        while (tokens[i + steps] === "=") steps++;
        const durationMs = steps * stepS * 1000 * (instrument.gate ?? 0.9);
        const at = i * stepS;
        if (instrument.wave === "noise") {
          s.noise({ durationMs, volume: instrument.volume, at,
            filter: instrument.filter, pan: instrument.pan, echo: instrument.echo });
        } else {
          const p = pitch(token);
          s.tone({ type: instrument.wave, from: p, to: p * (instrument.slide ?? 1),
            durationMs, volume: instrument.volume, at, attackMs: instrument.attackMs,
            detuneCents: instrument.detuneCents, vibrato: instrument.vibrato,
            pan: instrument.pan, echo: instrument.echo, filter: instrument.filter });
        }
      }
    }
  return wav(await ctx.startRendering());
}

const NOTES = { C: 0, "C#": 1, D: 2, "D#": 3, E: 4, F: 5, "F#": 6, G: 7, "G#": 8, A: 9, "A#": 10, B: 11 };
function pitch(name) {
  const m = /^([A-G]#?)(-?\\d)$/.exec(name);
  const midi = (Number(m[2]) + 1) * 12 + NOTES[m[1]];
  return 440 * Math.pow(2, (midi - 69) / 12);
}

/** An AudioBuffer → a 16-bit WAV blob. */
function wav(buf) {
  const ch = buf.numberOfChannels, n = buf.length;
  const out = new DataView(new ArrayBuffer(44 + n * ch * 2));
  const str = (o, s) => { for (let i = 0; i < s.length; i++) out.setUint8(o + i, s.charCodeAt(i)); };
  str(0, "RIFF"); out.setUint32(4, 36 + n * ch * 2, true); str(8, "WAVEfmt ");
  out.setUint32(16, 16, true); out.setUint16(20, 1, true); out.setUint16(22, ch, true);
  out.setUint32(24, buf.sampleRate, true); out.setUint32(28, buf.sampleRate * ch * 2, true);
  out.setUint16(32, ch * 2, true); out.setUint16(34, 16, true);
  str(36, "data"); out.setUint32(40, n * ch * 2, true);
  const data = Array.from({ length: ch }, (_, c) => buf.getChannelData(c));
  let o = 44;
  for (let i = 0; i < n; i++) {
    for (let c = 0; c < ch; c++) {
      const v = Math.max(-1, Math.min(1, data[c][i]));
      out.setInt16(o, v < 0 ? v * 0x8000 : v * 0x7fff, true);
      o += 2;
    }
  }
  return new Blob([out.buffer], { type: "audio/wav" });
}
