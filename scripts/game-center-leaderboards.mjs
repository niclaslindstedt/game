// THE PORTAL MANIFEST for the platform leaderboard list — what a human types
// into App Store Connect (Game Center) and, later, the Play Console. The exact
// peer of scripts/game-center-achievements.mjs.
//
// The platform half of leaderboards is the one part of the feature the game
// can't ship by itself: a board only exists once it has been created in the
// portal, and a score for an id that isn't there is dropped on the floor. So
// the manifest is GENERATED from the catalog and COMMITTED
// (native/store/game-center-leaderboards.json): the diff on a catalog change is
// exactly the work list of entries to add or retitle, and the test suite fails
// when the committed file drifts.
//
//   node scripts/game-center-leaderboards.mjs           # write + print
//   node scripts/game-center-leaderboards.mjs --check   # fail if it drifted
//
// The FORMAT column is not decoration. A Game Center score is an Int64, so the
// game scales a rate or a duration on its way out (`scale` here); if the
// portal's score format doesn't match that scale, every score on the board is
// silently wrong by a factor of a hundred — or read as a bare number where a
// clock was meant. The two are printed side by side for exactly that check.

import { readFileSync, writeFileSync } from "node:fs";
import { register } from "node:module";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..");

register(pathToFileURL(path.join(here, "game-alias-loader.mjs")).href);

const { PLATFORM_LEADERBOARD_LIMIT, leaderboardManifest } = await import(
  pathToFileURL(path.join(root, "pwa/src/game/platform-leaderboards.ts")).href
);

const OUT = path.join(root, "native/store/game-center-leaderboards.json");

const rows = leaderboardManifest();

const document = {
  $comment:
    "GENERATED by scripts/game-center-leaderboards.mjs — do not edit by hand. " +
    "Create/update these entries in App Store Connect (Game Center → Leaderboards); " +
    "the id column is the board's Leaderboard ID, and `format` MUST match `scale` " +
    "(the multiplier the game applies before submitting).",
  limit: PLATFORM_LEADERBOARD_LIMIT,
  count: rows.length,
  leaderboards: rows,
};
const body = `${JSON.stringify(document, null, 2)}\n`;

const check = process.argv.includes("--check");
if (check) {
  let current;
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    current = ""; // never generated — treat as maximally out of date
  }
  if (current !== body) {
    console.error(
      "game-center-leaderboards.json is out of date — run `node scripts/game-center-leaderboards.mjs`\n" +
        "then create any NEW entries in App Store Connect before shipping.",
    );
    process.exit(1);
  }
  console.log(`manifest up to date (${rows.length} leaderboards)`);
  process.exit(0);
}

writeFileSync(OUT, body);

const pad = (value, width) => String(value).padEnd(width);
const widest = rows.reduce((w, row) => Math.max(w, row.id.length), 0);
for (const row of rows) {
  console.log(
    `  ${pad(row.id, widest)}  ${pad(row.format, 26)}` +
      `x${pad(row.scale, 8)}${row.name}`,
  );
}
console.log(
  `\n${rows.length}/${PLATFORM_LEADERBOARD_LIMIT} leaderboards → ` +
    `${path.relative(root, OUT)}`,
);
