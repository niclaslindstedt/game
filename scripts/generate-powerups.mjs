#!/usr/bin/env node
// SPDX-License-Identifier: PolyForm-Noncommercial-1.0.0
// The POWERUP pipeline. Compiles `content/powerups.yaml` — the hand-authored
// catalog of every time-limited power a pickup can grant, and the single place
// their balance is tuned — into `src/generated/powerups.ts`
// (GENERATED_POWERUPS), which `src/game/defs/abilities.ts` re-exposes as
// ABILITY_DEFS. It:
//   1. harvests the sprite stems from the content/sprites tree, so an icon or
//      projectile sprite that isn't in the atlas fails the build,
//   2. schema-validates every powerup (a missing field, an unknown kind, a
//      param block that doesn't match the kind — see asset-tools/
//      powerup-schema.mjs),
//   3. writes the flat `{ id → AbilityDef }` catalog, stamping each def's `id`
//      from its catalog key so the YAML never repeats itself.
// The output is gitignored and regenerated on every build (like enemies.ts and
// levels.ts), so the YAML is the single source of truth.
//
//   node scripts/generate-powerups.mjs
//
// MUST run BEFORE generate-levels.mjs: the level pipeline cross-refs every
// level's `loot.abilityPool` against the live ability catalog, which now reads
// the file this script writes. Like the item pipeline it imports NOTHING from
// the engine — every ref it validates against comes from the content tree — so
// it can never join a bootstrap cycle.

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { parse } from "yaml";

import { validatePowerup } from "./asset-tools/powerup-schema.mjs";

const engine = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url));

// ---- Sprite stems (content/sprites/<family>/<name>.yaml, stem == sprite id;
// underscore-prefixed files are family/core preambles, not sprites). ----------
const spritesDir = engine("content/sprites");
const sprites = new Set();
for (const family of readdirSync(spritesDir, { withFileTypes: true })) {
  if (!family.isDirectory()) continue;
  for (const file of readdirSync(`${spritesDir}/${family.name}`)) {
    if (!file.endsWith(".yaml") || file.startsWith("_")) continue;
    sprites.add(file.slice(0, -".yaml".length));
  }
}

// ---- Load ------------------------------------------------------------------
const source = "content/powerups.yaml";
const doc = parse(readFileSync(engine(source), "utf8"));
if (!doc || typeof doc !== "object" || Array.isArray(doc)) {
  console.error(`${source}: expected a YAML mapping`);
  process.exit(1);
}
const catalog = doc.powerups;
if (!catalog || typeof catalog !== "object" || Array.isArray(catalog)) {
  console.error(`${source}: expected a "powerups:" mapping of id → powerup`);
  process.exit(1);
}

// ---- Validate --------------------------------------------------------------
const errors = [];
const warnings = [];
for (const [id, def] of Object.entries(catalog)) {
  const res = validatePowerup(id, def, { sprites });
  errors.push(...res.errors);
  warnings.push(...res.warnings);
}
for (const w of warnings) console.warn(`! ${w}`);
if (errors.length > 0) {
  console.error(
    `${errors.length} powerup schema error(s):\n  ${errors.join("\n  ")}`,
  );
  process.exit(1);
}

// ---- Compile ---------------------------------------------------------------
// The catalog key IS the id — stamped in here so the YAML never has to repeat
// it (and so the two can never disagree).
const powerups = {};
for (const [id, def] of Object.entries(catalog)) {
  powerups[id] = { id, ...def };
}

const banner = `// @generated by scripts/generate-powerups.mjs — DO NOT EDIT.
// Source of truth: content/powerups.yaml. Regenerate with
// \`npm run levels\` (also runs inside \`npm run assets\` / \`make assets\`).
// SPDX-License-Identifier: PolyForm-Noncommercial-1.0.0`;

const out = `${banner}
import type { AbilityDef } from "../game/defs/abilities.ts";

export const GENERATED_POWERUPS: Record<string, AbilityDef> = ${JSON.stringify(
  powerups,
  null,
  2,
)} as unknown as Record<string, AbilityDef>;
`;

const destDir = engine("src/generated");
mkdirSync(destDir, { recursive: true });
writeFileSync(`${destDir}/powerups.ts`, out);
console.log(
  `wrote src/generated/powerups.ts — ${Object.keys(powerups).length} powerups`,
);
