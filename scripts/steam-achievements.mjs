// THE PORTAL MANIFEST for Steam's achievement list — what a human types into
// the Steamworks partner site (App Admin → Achievements).
//
// The twin of scripts/game-center-achievements.mjs, and it exists for the same
// reason: an achievement only exists once it has been created in the portal,
// and a report for an id that isn't there is dropped on the floor. So the
// manifest is GENERATED from the live catalog and COMMITTED
// (electron/store/steam-achievements.json): the diff on a catalog change is
// exactly the work list of rows to add or retitle, and the test suite fails
// when the committed file drifts from the catalog.
//
//   node scripts/steam-achievements.mjs           # write + print
//   node scripts/steam-achievements.mjs --check   # fail if it drifted
//
// There is no point column, unlike Game Center's: Steam has no achievement
// point system at all. What it caps instead is the COUNT — a new app gets 100
// until it reaches Valve's Profile Features threshold, after which the whole
// catalog can ship (see `STEAM_FULL_CATALOG` in platform-achievements.ts).

import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { register } from "node:module";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..");

register(pathToFileURL(path.join(here, "game-alias-loader.mjs")).href);

const { PLATFORM_ACHIEVEMENT_LIMIT, STEAM_FULL_CATALOG, steamManifest } =
  await import(
    pathToFileURL(path.join(root, "pwa/src/game/platform-achievements.ts")).href
  );

const OUT = path.join(root, "electron/store/steam-achievements.json");

const rows = steamManifest();

const document = {
  $comment:
    "GENERATED by scripts/steam-achievements.mjs — do not edit by hand. " +
    "Create/update these rows in the Steamworks partner site " +
    "(App Admin → Achievements); the id column is the achievement's API Name.",
  limit: PLATFORM_ACHIEVEMENT_LIMIT,
  fullCatalog: STEAM_FULL_CATALOG,
  count: rows.length,
  achievements: rows,
};
const body = `${JSON.stringify(document, null, 2)}\n`;

// Steam's cap is on the COUNT, and it is the one thing here that can be
// violated silently — the portal simply refuses row 101, long after the catalog
// change that added it.
if (rows.length > PLATFORM_ACHIEVEMENT_LIMIT && !STEAM_FULL_CATALOG) {
  console.error(
    `${rows.length} achievements exceeds Steam's ${PLATFORM_ACHIEVEMENT_LIMIT} ` +
      "for an app that has not reached Profile Features yet.",
  );
  process.exit(1);
}

const check = process.argv.includes("--check");
if (check) {
  let current;
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    current = ""; // never generated — treat as maximally out of date
  }
  if (current !== body) {
    console.error(
      "steam-achievements.json is out of date — run `node scripts/steam-achievements.mjs`\n" +
        "then create any NEW rows in the Steamworks partner site before shipping.",
    );
    process.exit(1);
  }
  console.log(`manifest up to date (${rows.length} achievements)`);
  process.exit(0);
}

mkdirSync(path.dirname(OUT), { recursive: true });
writeFileSync(OUT, body);

const pad = (value, width) => String(value).padEnd(width);
const widest = rows.reduce((w, row) => Math.max(w, row.id.length), 0);
let category = "";
for (const row of rows) {
  if (row.category !== category) {
    category = row.category;
    console.log(`\n${category}`);
  }
  console.log(`  ${pad(row.id, widest)}  ${row.name}`);
}
console.log(
  `\n${rows.length} achievements → ${path.relative(root, OUT)} ` +
    `(cap ${PLATFORM_ACHIEVEMENT_LIMIT}${STEAM_FULL_CATALOG ? ", full catalog" : ""})`,
);
