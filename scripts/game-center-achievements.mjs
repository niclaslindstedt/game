// THE PORTAL MANIFEST for the platform achievement list — what a human types
// into App Store Connect (Game Center) and, later, the Play Console.
//
// The platform half of achievements is the one part of the feature the game
// can't ship by itself: an achievement only exists once it has been created in
// the portal, and a report for an id that isn't there is dropped on the floor.
// So the manifest is GENERATED from the live catalog and COMMITTED
// (native/store/game-center-achievements.json): the diff on a catalog change
// is exactly the work list of entries to add, retitle, or re-point, and the
// test suite fails when the committed file drifts from the catalog.
//
//   node scripts/game-center-achievements.mjs           # write + print
//   node scripts/game-center-achievements.mjs --check   # fail if it drifted
//
// The point column is not a preference: Game Center allows 100 achievements
// and 1,000 points TOTAL, so the budget is apportioned across the whole list
// from the badges' own tiers (pwa/src/game/platform-achievements.ts).

import { readFileSync, writeFileSync } from "node:fs";
import { register } from "node:module";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..");

register(pathToFileURL(path.join(here, "game-alias-loader.mjs")).href);

const { PLATFORM_ACHIEVEMENT_LIMIT, PLATFORM_POINT_BUDGET, platformManifest } =
  await import(
    pathToFileURL(path.join(root, "pwa/src/game/platform-achievements.ts")).href
  );

const OUT = path.join(root, "native/store/game-center-achievements.json");

const rows = platformManifest();
const points = rows.reduce((sum, row) => sum + row.points, 0);

const document = {
  $comment:
    "GENERATED by scripts/game-center-achievements.mjs — do not edit by hand. " +
    "Create/update these entries in App Store Connect (Game Center → Achievements); " +
    "the id column is the achievement's Achievement ID.",
  limit: PLATFORM_ACHIEVEMENT_LIMIT,
  pointBudget: PLATFORM_POINT_BUDGET,
  count: rows.length,
  points,
  achievements: rows,
};
const body = `${JSON.stringify(document, null, 2)}\n`;

const check = process.argv.includes("--check");
if (check) {
  let current;
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    current = ""; // never generated — treat as maximally out of date
  }
  if (current !== body) {
    console.error(
      "game-center-achievements.json is out of date — run `node scripts/game-center-achievements.mjs`\n" +
        "then create any NEW entries in App Store Connect before shipping.",
    );
    process.exit(1);
  }
  console.log(`manifest up to date (${rows.length} achievements)`);
  process.exit(0);
}

writeFileSync(OUT, body);

const pad = (value, width) => String(value).padEnd(width);
const widest = rows.reduce((w, row) => Math.max(w, row.id.length), 0);
let category = "";
for (const row of rows) {
  if (row.category !== category) {
    category = row.category;
    console.log(`\n${category.toUpperCase()}`);
  }
  console.log(
    `  ${pad(row.id, widest)}  ${pad(`${row.points} pts`, 8)}` +
      `${row.incremental ? "progress" : "one-shot"}  ${row.name}`,
  );
}
console.log(
  `\n${rows.length}/${PLATFORM_ACHIEVEMENT_LIMIT} achievements, ` +
    `${points}/${PLATFORM_POINT_BUDGET} points → ${path.relative(root, OUT)}`,
);
